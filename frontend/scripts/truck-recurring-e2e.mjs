import { expect } from '@playwright/test';
import { join } from 'node:path';

export async function runTruckRecurringE2E({page,base,temp}) {
  const session=await (await page.request.get(base+'/api/auth/session')).json();
  const headers={'x-csrf-token':session.csrfToken};
  const all=await (await page.request.get(base+'/api/drivers')).json();
  const driver=all.find(d=>d.fullName==='E2e Driver');
  const charges=await (await page.request.get(base+'/api/driver-charges')).json();
  const week=charges.currentWeek;
  await page.goto(base+'/trucks');
  await page.getByRole('button',{name:'Add truck',exact:true}).click();
  await page.getByLabel('Unit number',{exact:true}).fill('OWNER-AUTO');
  await page.getByLabel('Truck owner').selectOption(`driver:${driver.id}`);
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel(/Assigned driver/).selectOption(driver.id);
  // New trucks use the normal effective-assignment control.
  const assignment=dialog.getByLabel(/Assignment starts week/);
  if(await assignment.count()) await assignment.fill(week);
  await page.getByRole('button',{name:'Create truck',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  const trucks=await (await page.request.get(base+'/api/trucks')).json();
  const truck=trucks.find(t=>t.unitNumber==='OWNER-AUTO');
  expect(truck).toBeTruthy();
  const owner=await (await page.request.get(base+'/api/drivers/'+driver.id)).json();
  expect(owner.employmentType).toBe('owner_operator');
  expect(owner.isOwnerOperator).toBe(true);
  const investors=await (await page.request.get(base+'/api/investors')).json();
  expect(investors.filter(i=>i.driverId===driver.id)).toHaveLength(1);
  await page.goto(base+'/drivers/detail?id='+driver.id);
  await expect(page.getByText('Owner operator',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Edit driver',exact:true}).click();
  await expect(page.getByRole('dialog').getByLabel('Driver type',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  const created=await page.request.post(base+'/api/driver-charges/types',{headers,data:{name:'Truck insurance',direction:'charge',amount:'50',amounts:['50','75'],eligibility:'calendar',archived:false,version:0}});
  expect(created.ok()).toBe(true);
  const type=await created.json();
  await page.goto(base+'/accounting/driver-charges');
  await expect(page.getByRole('tab',{name:'Driver charges',exact:true})).toHaveCount(0);
  await page.getByRole('tab',{name:'Truck charges',exact:true}).click();
  const fee=page.getByLabel('OWNER-AUTO, Truck insurance',{exact:true});
  await expect(fee).toBeEnabled();
  await fee.check();
  await expect(page.getByRole('button',{name:'Reload',exact:true})).toBeEnabled();
  await page.getByLabel('OWNER-AUTO, Truck insurance amount',{exact:true}).selectOption('75.00');
  await expect(page.getByRole('button',{name:'Reload',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Show trucks included in Truck insurance',exact:true}).click();
  await expect(page.getByLabel('Truck inclusion')).toHaveValue('included');
  await expect(page.getByRole('link',{name:'OWNER-AUTO',exact:true})).toBeVisible();
  await page.screenshot({path:join(temp,'truck-recurring-desktop.png'),fullPage:true});
  const pay=await (await page.request.get(base+'/api/driver-pay?weekStart='+week)).json();
  const statement=pay.drivers.find(d=>d.id===driver.id);
  expect(statement.autoCharges.find(c=>c.source===`truck_charge:${truck.id}:${type.id}`).amount).toBe('-75.00');
  expect(statement.edits.generatedCharges??[]).toHaveLength(0);
  const rejected=await page.request.put(base+'/api/driver-charges/recurring',{headers,data:{driverId:driver.id,typeId:type.id,weekStart:week,amount:'50',included:true}});
  expect(rejected.status()).toBe(400);
  await page.getByRole('button',{name:'Collapse sidebar',exact:true}).click();
  await expect(page.locator('aside')).toHaveCSS('width','64px');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:join(temp,'truck-recurring-narrow.png'),fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Expand sidebar',exact:true}).click();
  // Pause this isolated fee so the installment/expense suite can continue.
  await fee.click();
  await expect(page.getByRole('button',{name:'Reload',exact:true})).toBeEnabled();
  await page.getByLabel('Truck inclusion').selectOption('all');
  await page.getByLabel('Filter truck charge type').selectOption('');
  const cleared=await page.request.put(base+'/api/trucks/'+truck.id,{headers,data:{unitNumber:truck.unitNumber,ownerId:truck.ownerId,driverId:null,status:'available',active:true,assignmentWeek:week}});
  expect(cleared.ok(),await cleared.text()).toBe(true);
  console.log('Truck recurring E2E passed: direct driver ownership, automatic classification, truck fees through payroll, removed driver writes, included-truck filters and mobile layout.');
}
