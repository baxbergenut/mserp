// Run against review-local.mjs after a /api build. Only synthetic local data.
import { chromium, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

const accessFile = process.env.MSERP_REVIEW_ACCESS_FILE;
const dsn = process.env.MSERP_REVIEW_TEST_DATABASE_URL;
if (!accessFile || !dsn) throw new Error('Set MSERP_REVIEW_ACCESS_FILE and MSERP_REVIEW_TEST_DATABASE_URL');
const { base, email, password, schema } = JSON.parse(await readFile(accessFile, 'utf8'));
const database = new URL(dsn);
if (!['127.0.0.1', 'localhost'].includes(database.hostname) || !database.pathname.endsWith('_test') || !/^review_[a-f0-9]+$/.test(schema) || !/^http:\/\/127\.0\.0\.1:\d+$/.test(base)) throw new Error('An isolated local review environment is required');
const sql = input => execFileSync(process.env.PSQL_PATH || 'psql', ['-X', '-q', '-v', 'ON_ERROR_STOP=1', '-d', dsn], { input: `SET search_path TO ${schema},public; ${input}`, encoding: 'utf8', windowsHide: true });
const driver = 'e4510000-0000-0000-0000-000000000001';
const number = 'PICKUP-TIME-E2E';
sql(`INSERT INTO drivers(id,full_name,normalized_name,pay_type,pay_rate) VALUES('${driver}','Pickup Time Driver','pickup time driver','cpm',0.6);
INSERT INTO loads(id,load_id,status,load_pay,total_pay,raw_payload) VALUES(989123,'${number}','dispatched',0,0,
'{"stops":[{"id":9891231,"ordering":1,"stop_type":"pickup","schedule_type":"window","scheduled_begin_date":"2026-10-30","scheduled_begin_time":"01:00:00","scheduled_end_date":"2026-10-30","scheduled_end_time":"02:00:00","location":{"city":"Dallas","state":"TX"}},{"id":9891232,"ordering":2,"stop_type":"delivery","schedule_type":"window","scheduled_begin_date":"2026-10-30","scheduled_begin_time":"01:30:00","scheduled_end_date":"2026-10-30","scheduled_end_time":"22:00:00","location":{"city":"Austin","state":"TX"}}]}');`);
const browser = await chromium.launch();
try {
  const context = await browser.newContext({ viewport: { width: 1920, height: 1000 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const login = await page.request.post(`${base}/api/auth/login`, { data: { email, password }, headers: { origin: base } });
  expect(login.ok()).toBe(true);
  const session = await (await page.request.get(`${base}/api/auth/session`)).json();
  const read = async () => (await (await page.request.get(`${base}/api/driver-board/loads/${driver}`)).json());
  const today = new Date().toLocaleDateString('en-CA', { timeZone: 'America/New_York' });
  const date = new Date(`${today}T12:00:00Z`);
  date.setUTCDate(date.getUTCDate() - (date.getUTCDay() + 6) % 7);
  const response = await page.request.get(`${base}/api/driver-board?weekStart=${date.toISOString().slice(0, 10)}`);
  expect(response.ok()).toBe(true);
  const board = await response.json();
  const entry = board.entries.find(e => e.driverId === driver);
  const view = await read();
  const add = await page.request.post(`${base}/api/driver-board/loads/${driver}`, { headers: { origin: base, 'x-csrf-token': session.csrfToken }, data: { action: 'add', number, version: entry.version, revision: view.revision, fromDate: view.fromDate } });
  expect(add.ok()).toBe(true);
  const added = await add.json();
  const unknown = await page.request.post(`${base}/api/driver-board/loads/${driver}`, { headers: { origin: base, 'x-csrf-token': session.csrfToken }, data: { action: 'add', number: 'WAITING-FOR-IMPORT', version: added.entry.version, revision: added.loads.revision, fromDate: added.loads.fromDate } });
  expect(unknown.ok()).toBe(true);
  await page.goto(`${base}/driver-board`);
  await page.getByLabel('Search Status Board', { exact: true }).fill('Pickup Time Driver');
  const pickup = page.getByRole('button', { name: 'Pickup Time Driver · Next pickup time', exact: true });
  const eta = page.getByRole('button', { name: 'Pickup Time Driver · ETA', exact: true });
  await expect(pickup).toHaveText('PU 02:00 FRI');
  await pickup.click();
  const editor = page.getByRole('dialog', { name: 'Pickup Time Driver · Next pickup time', exact: true });
  await expect(page.getByRole('dialog', { name: 'Pickup Time Driver · Loads', exact: true })).toHaveCount(0);
  await editor.getByLabel('Manual pickup time', { exact: true }).fill('03:00 FRI');
  await editor.getByRole('button', { name: 'Save time', exact: true }).click();
  await expect(pickup).toHaveText('PU 03:00 FRI');
  expect((await read()).next[0].stops[0].manualStopTime).toBe('03:00 FRI');
  // Reproduce the reported failure: refresh the provider timestamp while this
  // popup retains its source revision, then clear without closing/reloading.
  sql("UPDATE loads SET synced_at=synced_at+interval '1 minute' WHERE id=989123;");
  await editor.getByLabel('Manual pickup time', { exact: true }).fill('');
  await editor.getByRole('button', { name: 'Save time', exact: true }).click();
  await expect(pickup).toHaveText('PU 02:00 FRI');
  await expect(editor.getByRole('alert')).toHaveCount(0);
  await editor.getByLabel('Manual pickup time', { exact: true }).fill('03:00 FRI');
  await editor.getByRole('button', { name: 'Save time', exact: true }).click();
  await expect(pickup).toHaveText('PU 03:00 FRI');
  await editor.getByRole('button', { name: 'Close', exact: true }).click();
  await page.reload();
  await expect(pickup).toHaveText('PU 03:00 FRI');
  await pickup.click();
  await editor.getByLabel('Manual pickup time', { exact: true }).fill('');
  await editor.getByRole('button', { name: 'Save time', exact: true }).click();
  await expect(pickup).toHaveText('PU 02:00 FRI');
  await editor.getByLabel('Manual pickup time', { exact: true }).fill('04:00 FRI');
  await editor.getByRole('button', { name: 'Save time', exact: true }).click();
  await expect(pickup).toHaveText('PU 04:00 FRI');
  await editor.getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('button', { name: 'Pickup Time Driver · Next load', exact: true }).click();
  const queue = page.getByRole('dialog', { name: 'Pickup Time Driver · Loads', exact: true });
  await queue.getByRole('button', { name: number, exact: true }).click();
  await queue.getByRole('button', { name: 'Set current', exact: true }).click();
  await queue.getByRole('button', { name: 'Confirm current load', exact: true }).click();
  await queue.getByRole('button', { name: 'Close loads', exact: true }).click();
  await expect(eta).toHaveText('PU 04:00 FRI');
  await expect(pickup).toHaveCount(0);
  await page.reload();
  await expect(eta).toHaveText('PU 04:00 FRI');
  await page.getByRole('button', { name: 'Pickup Time Driver · Destination from load', exact: true }).click();
  await expect(eta).toHaveText('DEL TILL 22:00 FRI');
  await page.screenshot({ path: join(dirname(accessFile), 'status-board-pickup-times.png'), fullPage: true });
  expect(errors).toEqual([]);
  console.log('Real API/database pickup times passed: source window labels, targeted manual save, reload, clear, promotion to current, delivery cutoff and queue behavior.');
} finally {
  await browser.close();
  sql(`DELETE FROM drivers WHERE id='${driver}'; DELETE FROM loads WHERE id=989123;`);
}
