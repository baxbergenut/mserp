import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = readFileSync(new URL('../app/gross-board/planning.ts', import.meta.url), 'utf8');
const code = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
const {mergePlanningEntries, acknowledgePlanningDraft, planningLength, readPlanningDrafts, writePlanningDrafts} = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
const note={driverId:'d',date:'2026-11-02',kind:'note',text:'Ready later',version:1};
const destination={...note,kind:'destination',text:'Dallas, TX'};
assert.equal(planningLength('🚚'.repeat(1000)),1000);
assert.deepEqual(mergePlanningEntries([note,destination],[{...note,version:0,text:'stale'}]),[note,destination]);
assert.deepEqual(mergePlanningEntries([note],[]),[note]);
const cleared={...note,text:'',version:2};
assert.deepEqual(mergePlanningEntries([cleared],[note]),[cleared]);
assert.deepEqual(mergePlanningEntries([note],[cleared]),[cleared]);
assert.deepEqual(acknowledgePlanningDraft({note},note,{...note,version:2}),{});
assert.deepEqual(acknowledgePlanningDraft({note:{...note,text:'Newer'},destination},note,{...note,version:2}),{note:{...note,text:'Newer',version:2},destination});
assert.deepEqual(acknowledgePlanningDraft({},note,{...note,version:2}),{});
const storage=new Map();
globalThis.sessionStorage={getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,value),removeItem:key=>storage.delete(key)};
assert.equal(writePlanningDrafts('key',{note,destination}),true);
assert.deepEqual(readPlanningDrafts('key','d','2026-11-02'),{note,destination});
assert.deepEqual(readPlanningDrafts('key','other','2026-11-02'),{});
assert.deepEqual(readPlanningDrafts('key','d','2026-11-09'),{});
storage.set('key',JSON.stringify({savedAt:Date.now()-8*86400000,drafts:{note}}));
assert.deepEqual(readPlanningDrafts('key','d','2026-11-02'),{});
writePlanningDrafts('key',{});assert.equal(storage.has('key'),false);
sessionStorage.setItem=()=>{throw new Error('blocked')};assert.equal(writePlanningDrafts('key',{note}),false);
console.log('Planning helpers passed: independent kinds, Unicode limit, stale live snapshots, clear/recreate tombstones, queued typing, recovery scope/expiry and storage errors.');
