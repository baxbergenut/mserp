import { expect } from '@playwright/test';
import { join } from 'node:path';
import { verifyEscrow } from './escrow-e2e.mjs';

export async function verifyExpenseSettings(page, base, temp) {
  expect((await page.request.post(`${base}/api/expense-settings`, { data: { kind: 'category', name: 'No CSRF', active: true } })).status()).toBe(403);
  await page.goto(`${base}/expenses`);
  await page.getByRole('link', { name: 'Expenses & Charges settings', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Expenses & Charges settings', exact: true })).toBeVisible();
  await expect(page.getByLabel('Default driver escrow amount')).toHaveCount(0);
  await page.goto(`${base}/accounting/escrow`);
  const escrowDefault = page.getByLabel('Default driver escrow amount', { exact: true });
  await expect(escrowDefault).toHaveValue('2500.00');
  await escrowDefault.fill('2600');
  await page.getByRole('button', { name: 'Save default', exact: true }).click();
  await expect(escrowDefault).toHaveValue('2600.00');
  await page.goto(`${base}/drivers`);
  await page.getByRole('button', { name: 'Add driver', exact: true }).click();
  const setupEscrow = page.getByRole('spinbutton', { name: /^Escrow amount/ });
  await expect(setupEscrow).toHaveValue('2600.00');
  await page.getByLabel('Full name', { exact: true }).fill('Escrow Test Driver');
  await page.getByRole('spinbutton', { name: /^Rate per mile/ }).fill('0.75');
  await setupEscrow.fill('2650');
  await page.getByLabel('Hire date', { exact: true }).fill('2026-09-28');
  await page.getByRole('button', { name: 'Create driver', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const drivers = await (await page.request.get(`${base}/api/drivers?page=1&pageSize=100`)).json();
  const escrowDriver = drivers.items.find(driver => driver.fullName === 'Escrow Test Driver');
  expect(escrowDriver).toBeTruthy();
  const escrowExpenses = await (await page.request.get(`${base}/api/expenses?page=1&pageSize=100&chargeDriverId=${escrowDriver.id}`)).json();
  expect(escrowExpenses.items).toEqual([]);
  const driverRow = page.getByRole('row').filter({ has: page.getByText('Escrow Test Driver', { exact: true }) });
  await driverRow.getByRole('button', { name: 'Edit', exact: true }).click();
  await expect(page.getByRole('spinbutton', { name: /^Escrow amount/ })).toHaveCount(0);
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await verifyEscrow(page, base, temp, escrowDriver);
  await page.goto(`${base}/expenses/settings`);
  const add = async (kind, name) => {
    await page.getByRole('button', { name: `Add ${kind}`, exact: true }).click();
    await page.getByLabel('Setting name', { exact: true }).fill(name);
    await page.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
  };
  await add('category', 'E2E Travel');
  await add('expense name', 'E2E Hotel');
  await add('expense name', 'E2E Flight');
  await page.screenshot({ path: join(temp, 'expense-settings-categories.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('tab', { name: 'Payment methods', exact: true }).click();
  await add('payment method', 'E2E Card 1234');
  await page.getByRole('tab', { name: 'Paid by', exact: true }).click();
  await add('payer', 'E2E Accountant');
  await page.reload();
  await expect(page.getByRole('tab', { name: 'Paid by', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByText('E2E Accountant', { exact: true })).toBeVisible();
  await page.goto(`${base}/expenses`);
  await page.getByRole('button', { name: 'Add entry', exact: true }).click();
  const names = () => page.locator('#expense-names option').evaluateAll(options => options.map(option => option.value));
  await page.getByLabel('Category', { exact: true }).selectOption({ label: 'Maintenance' });
  expect(await names()).toContain('Tire replacement');
  await page.getByLabel('Name', { exact: true }).fill('Tire replacement');
  await page.getByLabel('Category', { exact: true }).selectOption({ label: 'Penalties' });
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('');
  expect(await names()).toContain('Parking violation');
  expect(await names()).not.toContain('Tire replacement');
  await page.getByLabel('Name', { exact: true }).fill('E2E Custom purchase');
  await page.getByLabel('Category', { exact: true }).selectOption({ label: 'E2E Travel' });
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('E2E Custom purchase');
  expect(await names()).toEqual(['E2E Flight', 'E2E Hotel']);
  await page.getByLabel('Amount', { exact: true }).fill('25');
  await page.getByLabel('Payment method', { exact: true }).fill('E2E Card 1234');
  expect(await page.locator('#payment-types option').evaluateAll(options => options.map(option => option.value))).toContain('E2E Card 1234');
  await page.getByRole('button', { name: 'Create entry', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  let settings = await (await page.request.get(`${base}/api/expense-settings`)).json();
  expect(settings.some(item => item.name === 'E2E Custom purchase')).toBe(false);
  const expenses = await (await page.request.get(`${base}/api/expenses?page=1&pageSize=100`)).json();
  const saved = expenses.items.find(item => item.expenseType === 'E2E Custom purchase');
  expect(saved.category).toBe('E2E Travel');
  await page.getByRole('link', { name: 'Expenses & Charges settings', exact: true }).click();
  await page.getByRole('tab', { name: 'Categories & names', exact: true }).click();
  await page.getByRole('button', { name: 'Edit category E2E Travel', exact: true }).click();
  await page.getByLabel('Setting name', { exact: true }).fill('E2E Trips');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByText('E2E Hotel', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Archive expense name E2E Flight', exact: true }).click();
  await page.getByRole('button', { name: 'Archive', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByText('E2E Flight', { exact: true })).toHaveCount(0);
  await page.getByRole('tab', { name: 'Payment methods', exact: true }).click();
  await page.getByRole('button', { name: 'Archive payment method E2E Card 1234', exact: true }).click();
  await page.getByRole('button', { name: 'Archive', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('Show archived', { exact: true }).check();
  await expect(page.getByRole('button', { name: 'Restore payment method E2E Card 1234', exact: true })).toBeVisible();
  await page.goto(`${base}/expenses`);
  const row = page.getByRole('row').filter({ has: page.getByText('E2E Custom purchase', { exact: true }) });
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  await expect(page.getByLabel('Category', { exact: true }).locator('option:checked')).toHaveText('E2E Trips');
  await expect(page.getByLabel('Payment method', { exact: true })).toHaveValue('E2E Card 1234');
  expect(await page.locator('#payment-types option').evaluateAll(options => options.map(option => option.value))).not.toContain('E2E Card 1234');
  await page.getByLabel('Amount', { exact: true }).fill('26');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  // Stub only the model response; reviewed expense writes still use the real API.
  const penaltyCategory = settings.find(item => item.kind === 'category' && item.name === 'Penalties');
  const draft = { company: 'MS Express', category: 'E2E Trips', categoryId: saved.categoryId, expenseType: 'E2E Hotel', expenseDate: '2026-09-28', amount: '12.50', paymentType: '', truckId: null, driverId: null, unitNumber: '', driverName: '', referenceNumber: '', description: '', coveredBy: 'Company', paidBy: '', confidence: 1, evidence: [] };
  await page.route('**/api/expenses/extract', route => route.fulfill({ json: { expenses: [draft, { ...draft, category: 'Penalties', categoryId: penaltyCategory.id, expenseType: 'Parking violation' }] } }));
  await page.getByRole('button', { name: 'Add entry', exact: true }).click();
  await page.getByPlaceholder('Paste one or more transactions, receipt text, invoice details…').fill('Two test receipts');
  await page.getByRole('button', { name: /Analyze/ }).click();
  await expect(page.getByLabel('Transaction 1 category', { exact: true }).locator('option:checked')).toHaveText('E2E Trips');
  expect(await page.locator('#transaction-0-names option').evaluateAll(options => options.map(option => option.value))).toEqual(['E2E Hotel']);
  await page.getByLabel('Transaction 1 category', { exact: true }).selectOption({ label: 'Penalties' });
  await expect(page.getByLabel('Transaction 1 name', { exact: true })).toHaveValue('');
  expect(await page.locator('#transaction-0-names option').evaluateAll(options => options.map(option => option.value))).not.toContain('Tire replacement');
  await page.getByLabel('Transaction 1 name', { exact: true }).fill('E2E Custom penalty');
  await page.getByRole('button', { name: 'Create 2 entries', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.unroute('**/api/expenses/extract');
  await page.goto(`${base}/expenses/settings`);
  await page.getByRole('tab', { name: 'Categories & names', exact: true }).click();
  await page.getByRole('button', { name: 'Archive category E2E Trips', exact: true }).click();
  await page.getByRole('button', { name: 'Archive', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.goto(`${base}/expenses`);
  await page.getByRole('button', { name: 'Add entry', exact: true }).click();
  expect(await page.getByLabel('Category', { exact: true }).locator('option').allTextContents()).not.toContain('E2E Trips');
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.goto(`${base}/expenses/settings`);
  await page.getByRole('button', { name: 'Restore category E2E Trips', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Archive category E2E Trips', exact: true })).toBeEnabled();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Collapse sidebar' }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: join(temp, 'expense-settings-mobile.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Expand sidebar' }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${base}/accounting/driver-charges`);
}
