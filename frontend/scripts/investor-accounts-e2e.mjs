import { expect } from '@playwright/test';
import { join } from 'node:path';

export async function runInvestorAccountsE2E({page,base,temp,sql,schema}) {
  const {currentWeek}=await (await page.request.get(base+'/api/driver-charges')).json();
  const prior=new Date(Date.parse(currentWeek)-7*86400000).toISOString().slice(0,10);
  sql(`SET search_path TO ${schema},public;
    INSERT INTO investors(id,full_name) VALUES('20200000-0000-0000-0000-000000000001','Account Investor');
    INSERT INTO trucks(id,unit_number,owner_id) VALUES('20200000-0000-0000-0000-000000000002','043','20200000-0000-0000-0000-000000000001');
    INSERT INTO truck_settlement_terms(truck_id,owner_id,week_start,share_percent) VALUES('20200000-0000-0000-0000-000000000002','20200000-0000-0000-0000-000000000001','${prior}',90);
    INSERT INTO drivers(id,full_name,normalized_name,pay_type,pay_rate) VALUES('20200000-0000-0000-0000-000000000010','Owner Operator','owner operator','gross_percentage',90);
    INSERT INTO investors(id,full_name,driver_id) VALUES('20200000-0000-0000-0000-000000000011','Owner Operator','20200000-0000-0000-0000-000000000010');
    INSERT INTO trucks(id,unit_number,owner_id) VALUES('20200000-0000-0000-0000-000000000012','OWN-045','20200000-0000-0000-0000-000000000011');
    INSERT INTO truck_driver_assignments(truck_id,driver_id,assigned_at) VALUES('20200000-0000-0000-0000-000000000012','20200000-0000-0000-0000-000000000010','2026-01-01');
    UPDATE driver_escrows SET start_date='${prior}' WHERE truck_id='20200000-0000-0000-0000-000000000002';`);
  await page.reload();
  await page.getByRole('tab',{name:'Installment plans',exact:true}).click();
  await page.getByRole('button',{name:'New installment plan',exact:true}).click();
  await page.getByLabel('Plan for',{exact:true}).selectOption('truck');
  await expect(page.getByLabel('Investor truck',{exact:true}).locator('option[value="20200000-0000-0000-0000-000000000012"]')).toHaveCount(0);
  await page.getByLabel('Investor truck',{exact:true}).selectOption({label:'Account Investor - Truck 043'});
  await page.getByLabel('Description',{exact:true}).fill('Truck repair');
  await page.getByLabel('Total charge',{exact:true}).fill('300');
  await page.getByLabel('Weekly amount',{exact:true}).fill('100');
  await page.getByLabel('Start week (Monday)',{exact:true}).fill(prior);
  await page.getByRole('button',{name:'Preview schedule',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('Account Investor - Truck 043');
  await page.getByRole('button',{name:'Create assignments',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('link',{name:'Account Investor - Truck 043',exact:true})).toBeVisible();
  await page.goto(base+'/accounting/escrow');
  const row=page.getByRole('row').filter({hasText:'Account Investor - Truck 043'});
  await expect(row).toBeVisible();
  await expect(page.getByRole('row').filter({hasText:'Owner Operator - Truck OWN-045'})).toHaveCount(0);
  await row.getByRole('button',{name:'Payment history'}).click();
  await page.getByRole('button',{name:'Change balance',exact:true}).click();
  await page.getByLabel('New balance ($)',{exact:true}).fill('200');
  await page.getByLabel('Correction reason',{exact:true}).fill('Opening balance verified');
  await page.getByRole('button',{name:'Save balance',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await row.getByRole('button',{name:'Release',exact:true}).click();
  await page.getByLabel('Release amount',{exact:true}).fill('50');
  await page.getByRole('dialog').getByRole('button',{name:'Release',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(row).toContainText('150.00');
  await page.screenshot({path:join(temp,'investor-escrow.png'),fullPage:true});
  await page.goto(`${base}/accounting/investor-pay?weekStart=${prior}`);
  const expand=page.getByRole('button',{name:'Account Investor 043',exact:true});
  if(await expand.getAttribute('aria-expanded')!=='true')await expand.click();
  const amount=page.getByLabel('Account Investor, Truck repair, charge amount',{exact:true});
  await expect(amount).toHaveValue('-100.00');
  await amount.fill('-25');await amount.press('Tab');
  await expect(page.getByText('Saved',{exact:true})).toBeVisible({timeout:15000});
  await page.reload();
  if(await expand.getAttribute('aria-expanded')!=='true')await expand.click();
  await expect(amount).toHaveValue('-25.00');
  await page.screenshot({path:join(temp,'investor-installment-pay.png'),fullPage:true});
}
