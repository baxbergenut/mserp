// Real API/database saves in an isolated review-local environment.
import { readFile } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';

const access = JSON.parse(await readFile(process.env.MSERP_REVIEW_ACCESS_FILE, 'utf8'));
if (!['localhost', '127.0.0.1'].includes(new URL(access.base).hostname) || !/^review_[a-f0-9]+$/.test(access.schema)) throw new Error('Isolated local review required');
const browser = await chromium.launch();
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  const maintenanceDescription='Unified maintenance expense '+Date.now();
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(access.base+'/login');
  await page.getByLabel('Email or existing username').fill(access.email);
  await page.getByLabel('Password',{exact:true}).fill(access.password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.waitForURL(url=>!url.pathname.startsWith('/login'));
  const api=async path=>{const result=await page.request.get(access.base+'/api'+path);expect(result.ok(),await result.text()).toBe(true);return result.json();};
  const listing=await api('/expenses');
  const options=await api('/maintenance/options');
  const other=listing.options.settings.find(s=>s.kind==='category' && s.name==='Other');
  const truck=options.trucks[0];
  await page.goto(access.base+'/expenses');
  await expect(page.getByRole('link',{name:'Work orders',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Add entry',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await page.getByLabel('Category',{exact:true}).selectOption(other.id);
  await expect(page.getByRole('button',{name:'Add cost',exact:true})).toHaveCount(0);
  await expect(page.getByLabel('Odometer',{exact:true})).toHaveCount(0);
  await page.getByLabel('Expense type',{exact:true}).selectOption('__custom');
  await page.getByLabel('Expense type custom',{exact:true}).fill('Simple total expense');
  await page.getByLabel('Description',{exact:true}).fill('Regular expense without breakdown');
  await page.getByLabel('Amount',{exact:true}).fill('12.50');
  await page.getByRole('button',{name:'Create entry',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  // Current readings autofill new, today-dated entries only. Truck/date changes
  // invalidate automatic readings; manual values and late user edits win.
  const today=new Intl.DateTimeFormat('en-CA',{timeZone:'America/New_York',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
  const historical='2026-09-01';
  const secondTruck=options.trucks.find(t=>t.id!==truck.id);
  const readings=[], readingReplies=[];
  await page.route('**/api/maintenance/odometer?*',async route=>{
    const id=new URL(route.request().url()).searchParams.get('truckId');readings.push(id);
    await new Promise(resolve=>setTimeout(resolve,150));
    await route.fulfill({json:{reading:{mileage:id===truck.id?390000:390500,reportedAt:new Date().toISOString(),source:'samsara'},message:''}}).catch(()=>{});
    readingReplies.push(id);
  });
  await page.getByRole('button',{name:'Add entry',exact:true}).click();
  await page.getByLabel('Category',{exact:true}).selectOption(options.categoryId);
  await page.getByLabel('Expense type',{exact:true}).selectOption('Electrical');
  await expect(page.getByLabel('Oil type',{exact:true})).toHaveCount(0);
  await page.getByLabel('Expense type',{exact:true}).selectOption('Oil change');
  await expect(page.getByRole('combobox',{name:'Oil type',exact:true})).toBeVisible();
  await page.getByLabel('Oil type',{exact:true}).selectOption('15W-40');
  await page.getByLabel('Expense date',{exact:true}).fill(today);
  await page.getByLabel('Unit number',{exact:true}).selectOption(truck.id);
  await expect(page.getByLabel('Odometer',{exact:true})).toHaveValue('390000');
  await expect(page.getByText(/^Samsara ·/)).toBeVisible();
  await page.getByLabel('Odometer',{exact:true}).fill('390123');
  await page.getByLabel('Expense date',{exact:true}).fill(historical);
  await expect(page.getByLabel('Odometer',{exact:true})).toHaveValue('390123');
  const beforeHistorical=readings.length;
  await page.getByLabel('Unit number',{exact:true}).selectOption(secondTruck.id);
  await expect(page.getByLabel('Odometer',{exact:true})).toHaveValue('');
  await page.getByLabel('Expense date',{exact:true}).fill(today);
  await expect(page.getByLabel('Odometer',{exact:true})).toHaveValue('390500');
  expect(readings.slice(beforeHistorical)).toEqual([secondTruck.id]);
  await page.getByLabel('Expense date',{exact:true}).fill(historical);
  await expect(page.getByLabel('Odometer',{exact:true})).toHaveValue('');
  const beforeRace=readingReplies.length;
  await page.getByLabel('Expense date',{exact:true}).fill(today);
  await page.getByLabel('Odometer',{exact:true}).fill('391000');
  await page.getByLabel('Description',{exact:true}).fill('Keep manual reading while telemetry completes');
  await page.getByLabel('Oil type',{exact:true}).selectOption('custom');
  await page.getByLabel('Custom oil type',{exact:true}).fill('20w-50');
  await expect(page.getByLabel('Custom oil type',{exact:true})).toHaveValue('20W-50');
  await expect.poll(()=>readingReplies.length).toBeGreaterThan(beforeRace);
  await expect(page.getByLabel('Odometer',{exact:true})).toHaveValue('391000');
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('button',{name:'Add entry',exact:true}).click();
  await page.getByLabel('Description',{exact:true}).fill(maintenanceDescription);
  await page.getByLabel('Amount',{exact:true}).fill('120.30');
  await page.getByLabel('Category',{exact:true}).selectOption(options.categoryId);
  await expect(dialog).toHaveCount(1);
  await expect(page.getByRole('heading',{name:'Add entry',exact:true})).toBeVisible();
  await expect(page.getByLabel('Description',{exact:true})).toHaveValue(maintenanceDescription);
  await expect(page.getByLabel('Amount',{exact:true})).toHaveValue('120.30');
  await expect(page.getByLabel('Service date',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('Invoice',{exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Add cost',exact:true})).toHaveCount(0);
  await page.getByLabel('Expense type',{exact:true}).selectOption('Oil change');
  await page.getByLabel('Expense date',{exact:true}).fill('2026-10-22');
  await page.getByLabel('Unit number',{exact:true}).selectOption(truck.id);
  await page.getByLabel('Who will cover',{exact:true}).selectOption('Company');
  await page.getByLabel('Odometer',{exact:true}).fill('400000');
  await page.getByLabel('Oil type',{exact:true}).selectOption('10W-30');
  const shop=options.vendors.find(v=>v.active);
  await page.getByLabel('Shop',{exact:true}).selectOption(shop.id);
  await expect(page.getByLabel('Shop name',{exact:true})).toHaveValue(shop.name);
  await page.getByLabel('Shop address',{exact:true}).fill('101 Repair Lane');
  await page.getByLabel('Shop phone',{exact:true}).fill('5551234567');
  await page.getByLabel('Shop contact',{exact:true}).fill('Service desk');
  await page.getByLabel('Upload receipt / invoice',{exact:true}).setInputFiles({name:'maintenance-receipt.txt',mimeType:'text/plain',buffer:Buffer.from('Synthetic maintenance receipt $120.30')});
  await page.getByRole('button',{name:'Create entry',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  const after=await api('/expenses?search='+encodeURIComponent(maintenanceDescription));
  expect(after.items).toHaveLength(1);
  const saved=after.items[0];
  expect(saved.category).toBe('Maintenance');
  expect(saved.amount).toBe('120.30');
  expect(saved.costBreakdown).toEqual([]);
  expect(saved.maintenance).toMatchObject({odometer:400000,vendorName:shop.name,vendorAddress:'101 Repair Lane',vendorPhone:'5551234567',vendorContact:'Service desk',oilType:'10W-30'});
  expect(await api(`/expenses/${saved.id}/documents`)).toHaveLength(1);
  await page.reload();
  await page.getByRole('row',{name:'Open '+maintenanceDescription,exact:true}).click();
  await expect(page.getByLabel('Odometer',{exact:true})).toHaveValue('400000');
  await expect(page.getByRole('link',{name:'maintenance-receipt.txt',exact:true})).toBeVisible();
  await page.getByLabel('Shop address',{exact:true}).fill('202 Updated Lane');
  await page.getByLabel('Amount',{exact:true}).fill('130.30');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  const updated=await api('/expenses/'+saved.id);
  expect(updated.amount).toBe('130.30');
  expect(updated.maintenance.vendorAddress).toBe('202 Updated Lane');
  await page.goto(access.base+'/maintenance/detail?id='+saved.maintenance.recordId);
  await page.waitForURL(url=>url.pathname==='/expenses' && url.searchParams.get('expenseId')===saved.id);
  await expect(page.getByLabel('Odometer',{exact:true})).toHaveValue('400000');
  await expect(page.getByRole('button',{name:'Save changes',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  // AI review uses the same form and discards obsolete breakdown payloads.
  const aiDescription='AI unified maintenance expense '+Date.now();
  await page.route('**/api/expenses/extract',route=>route.fulfill({json:{expenses:[{categoryId:options.categoryId,category:'Maintenance',expenseType:'Oil change',expenseDate:'2026-10-23',truckId:truck.id,driverId:null,unitNumber:truck.unitNumber,driverName:'',amount:'150.00',paymentType:'',referenceNumber:'',description:aiDescription,coveredBy:'Company',paidBy:'',costBreakdown:[{name:'Obsolete detail',amount:'150.00'}],maintenance:{vendorName:'AI repair shop',vendorAddress:'AI address',vendorPhone:'5559876543',vendorContact:'AI service desk',odometer:401000,oilType:'15W-40',location:'shop'}}]}}));
  await page.getByRole('button',{name:'Add entry',exact:true}).click();
  await page.getByLabel('Expense details for AI').fill(aiDescription);
  await page.getByRole('button',{name:'Analyze',exact:true}).click();
  await expect(page.getByLabel('Shop name',{exact:true})).toHaveValue('AI repair shop');
  await expect(page.getByLabel('Odometer',{exact:true})).toHaveValue('401000');
  await expect(page.getByLabel('Expense date',{exact:true})).toHaveValue('2026-10-23');
  await expect(page.getByRole('button',{name:'Add cost',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Create entry',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  const aiSaved=(await api('/expenses?search='+encodeURIComponent(aiDescription))).items[0];
  expect(aiSaved.costBreakdown).toEqual([]);
  expect(aiSaved.maintenance.vendorName).toBe('AI repair shop');
  const session=await api('/auth/session');
  const retired=await page.request.post(access.base+'/api/maintenance',{headers:{'X-CSRF-Token':session.csrfToken,Origin:access.base},data:{expense:{categoryId:options.categoryId}}});
  expect(retired.status()).toBe(410);
  const legacyResponse=await page.request.post(access.base+'/api/expenses',{headers:{'X-CSRF-Token':session.csrfToken,Origin:access.base},data:{categoryId:options.categoryId,expenseType:'Electrical',expenseDate:'2026-10-01',amount:'100.00',paymentType:'EFS',paidBy:'Local Review',coveredBy:'Company',description:'Legacy EFS expense total',maintenance:{odometer:null,vendorId:null,vendorName:'Legacy shop',vendorAddress:'',vendorPhone:'',vendorContact:'',oilType:''}}});
  expect(legacyResponse.status()).toBe(201);
  const legacy=await legacyResponse.json();
  expect(legacy.baseAmount).toBeNull();
  await page.goto(access.base+'/expenses?expenseId='+legacy.id);
  await expect(page.getByLabel('Amount',{exact:true})).toHaveValue('100.00');
  await page.getByLabel('Shop name',{exact:true}).fill('Updated legacy shop');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  const unchanged=await api('/expenses/'+legacy.id);
  expect(unchanged.amount).toBe('100.00');
  expect(unchanged.baseAmount).toBeNull();
  expect(unchanged.paymentFee).toBe('0.00');
  const anonymous=await browser.newContext();
  expect((await anonymous.request.get(access.base+'/api/expenses/'+saved.id)).status()).toBe(401);
  await anonymous.close();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('row',{name:'Open '+maintenanceDescription,exact:true}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await expect(page.getByRole('button',{name:'Add cost',exact:true})).toHaveCount(0);
  await page.screenshot({path:process.env.MSERP_MAINTENANCE_SCREENSHOT || 'maintenance-expense-mobile.png',fullPage:true,animations:'disabled'});
  expect(errors).toEqual([]);
  console.log('PASS: shared expense modal, oil-only grade dropdown, guarded odometer autofill and manual/AI preservation, shop details, totals, receipts, edits, legacy links and mobile layout.');
} finally {await browser.close();}
