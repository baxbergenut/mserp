import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../app/driver-board/board.ts', import.meta.url), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 } });
const { reconcileDriverBoard, parseETA, formatETA } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const draft = { driverId: 'a', notes: 'first', driverHome: 'Memphis, TN', version: 0, homeVersion: 0 };
const committed = { ...draft, version: 1, homeVersion: 1 };
assert.deepEqual(reconcileDriverBoard({ a: draft }, { a: draft }, [committed]), {});
const later = { ...draft, notes: 'second', driverHome: 'Louisville, KY' };
assert.deepEqual(reconcileDriverBoard({ a: later }, { a: draft }, [committed]), { a: { ...later, version: 1, homeVersion: 1 } });
const reverted = { ...draft, notes: '' };
assert.deepEqual(reconcileDriverBoard({ a: reverted }, { a: draft }, [committed]), { a: { ...reverted, version: 1, homeVersion: 1 } });
assert.deepEqual(reconcileDriverBoard({ b: { ...draft, driverId: 'b' } }, { a: draft }, [committed]), { b: { ...draft, driverId: 'b' } });
console.log('Driver Board checks passed: in-flight typing, revert and version reconciliation.');
assert.deepEqual(parseETA('2026-10-03T14:30'), { date: '2026-10-03', time: '14:30' });
assert.deepEqual(parseETA('2026-10-03'), { date: '2026-10-03', time: '' });
assert.equal(parseETA('2026-02-30'), null);
assert.equal(parseETA('2026-10-03T24:01'), null);
assert.equal(parseETA('Friday 17:00'), null);
assert.equal(formatETA('Friday 17:00'), 'Friday 17:00');
assert.equal(formatETA('2026-10-03T14:30'), '10/3 · 2:30p');
assert.equal(formatETA('2026-10-03T00:00'), '10/3 · 12:00a');
assert.equal(formatETA('2026-10-03T12:00'), '10/3 · 12:00p');
assert.equal(formatETA('2026-10-03'), '10/3');
assert.equal(formatETA('2026-10-03T14:30', true), '2026-10-03 · 2:30pm · New York time');
console.log('ETA checks passed: compact date/time, date-only, midnight/noon, invalid dates and preserved legacy text.');

const stateSource = fs.readFileSync(new URL('../app/lib/usStates.ts', import.meta.url), 'utf8');
const statesJS = ts.transpileModule(stateSource, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { compactLoadLocation } = await import('data:text/javascript;base64,' + Buffer.from(statesJS).toString('base64'));
assert.equal(compactLoadLocation('Dallas, Texas, 75236'), 'Dallas, TX');
assert.equal(compactLoadLocation('Dallas, tx, 75236-1234'), 'Dallas, TX');
assert.equal(compactLoadLocation('New York, New York 10001'), 'New York, NY');
assert.equal(compactLoadLocation('Boston, MA'), 'Boston, MA');
assert.equal(compactLoadLocation('Toronto, Ontario'), 'Toronto, Ontario');
assert.equal(compactLoadLocation(''), '');
console.log('Imported stop display checks passed: state abbreviations and ZIP removal.');
